// Generates everything that is derived from the source, so the docs cannot drift from the code:
//
//   toolkit/              the files to copy into your own project (tokens, helpers, CSS, script)
//   docs/charts/          one reference page per chart, plus an index
//   skills/productscope-charts/{assets,references}   the same files, packaged for the Claude skill
//   llms.txt, llms-full.txt   plain-text docs for AI assistants
//
// Run `npm run docs` after changing a chart, its options or its snippet. `npm run docs:check` (used by CI)
// regenerates in memory and fails if any generated file on disk is out of date.

import fs from "node:fs";
import path from "node:path";
import { loadSource, ROOT } from "./load-source.mjs";

const CHECK = process.argv.includes("--check");
const REPO = "https://github.com/DavidLortalPM/productscope-charts";
const RAW = "https://raw.githubusercontent.com/DavidLortalPM/productscope-charts/main";
const SITE = "https://charts.productscope.uk";
const SKILL = "skills/productscope-charts";

const S = await loadSource();
const { PAGES, GROUPS, HELPERS, CHARTS_CSS, CHARTS_JS, SHOW_CSS } = S;

const out = new Map(); // relative path -> content
const put = (rel, content) => out.set(rel, content.replace(/\r\n/g, "\n").replace(/\s+$/, "") + "\n");
const read = rel => fs.readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n");
const slug = p => p.path.slice(1);
const byPath = new Map(PAGES.map(p => [p.path, p]));
const NOTE_MD = "<!-- Generated by scripts/build-docs.mjs from the source in src/. Do not edit by hand: change the source and run `npm run docs`. -->";
const NOTE_CODE = "Generated by scripts/build-docs.mjs from the source in src/. Do not edit by hand: change the source and run `npm run docs`.";

// ---------------------------------------------------------------- checks that fail the build
const problems = [];
if (/`|\$\{/.test(CHARTS_JS) || /`|\$\{/.test(CHARTS_CSS) || /`|\$\{/.test(HELPERS)) {
  problems.push("The toolkit script, CSS or helpers contain a backtick or a dollar-brace sequence. They are stored as template literals, so neither is allowed.");
}
const listed = GROUPS.flatMap(g => g.paths);
for (const p of PAGES) if (!listed.includes(p.path)) problems.push(`${p.path} is in PAGES but not in any group in src/groups.ts.`);
for (const x of listed) if (!byPath.has(x)) problems.push(`${x} is in src/groups.ts but has no page in PAGES.`);
if (new Set(PAGES.map(p => p.path)).size !== PAGES.length) problems.push("Two pages share a path.");
for (const p of PAGES) {
  for (const f of ["name", "title", "tag", "when", "keys", "snippet"]) if (!p[f]) problems.push(`${p.path} has no ${f}.`);
  if (!p.opts?.length) problems.push(`${p.path} documents no options.`);
  try { new Function(p.snippet); } catch (e) { problems.push(`The snippet for ${p.path} is not valid JavaScript: ${e.message}`); }
}
try { new Function(CHARTS_JS); } catch (e) { problems.push(`The toolkit script does not parse: ${e.message}`); }

const fail = () => {
  console.error("Docs build failed:\n" + problems.map(p => "  - " + p).join("\n"));
  process.exit(1);
};
if (problems.length) fail(); // stop before generating anything from a broken source

// ---------------------------------------------------------------- tokens
const block = re => (SHOW_CSS.match(re) || [])[1];
const lightBlock = block(/:root\{([^}]*)\}/);
const darkBlock = block(/:root\[data-theme="dark"\]\{([^}]*)\}/);
if (!lightBlock || !darkBlock) problems.push("Could not find the light and dark token blocks in SHOW_CSS (src/shell.ts).");
const WANTED = ["bg", "surface", "sunk", "ink", "ink-2", "muted", "line", "line-2", "accent", "accent-ink", "ok", "guess", "decide",
  "c1", "c2", "c3", "c4", "c5", "c6", "c7", "c8", "c9", "f-ui", "r"];
const decls = text => new Map((text || "").split(";").map(d => d.trim()).filter(Boolean).map(d => { const i = d.indexOf(":"); return [d.slice(0, i).trim(), d.slice(i + 1).trim()]; }));
const SAME_IN_BOTH = ["f-ui", "r"]; // font and radius do not change between themes
const pick = (text, names) => { const m = decls(text); return names.map(n => { if (!m.has("--" + n)) problems.push(`Token --${n} is missing from the theme in src/shell.ts.`); return `  --${n}: ${m.get("--" + n)};`; }); };
const light = pick(lightBlock, WANTED), dark = pick(darkBlock, WANTED.filter(n => !SAME_IN_BOTH.includes(n)));
const TOKENS_CSS = `/* ${NOTE_CODE} */
/* Design tokens read by the charts. Edit the values to match your theme; keep the names. */
:root {
${light.join("\n")}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.map(l => "  " + l).join("\n")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${dark.join("\n")}
  color-scheme: dark;
}`;
// every token the toolkit reads must be defined above
const defined = new Set(WANTED);
const used = new Set([...(CHARTS_CSS + CHARTS_JS + HELPERS).matchAll(/var\(--([\w-]+)/g)].map(m => m[1]));
for (const t of used) if (!defined.has(t)) problems.push(`The toolkit reads var(--${t}) but toolkit/tokens.css does not define it (add it to WANTED in scripts/build-docs.mjs and the theme in src/shell.ts).`);

const HELPERS_JS = `/* ${NOTE_CODE} */\n/* Define these before toolkit.js. Change gbp and money0 for another currency (compact() in toolkit.js also hard-codes the pound sign). */\n${HELPERS}`;
const TOOLKIT_CSS = `/* ${NOTE_CODE} */\n${CHARTS_CSS.trim()}`;
const TOOLKIT_JS = `/* ${NOTE_CODE} */\n/* Needs helpers.js first (h, money0, legend) and the design tokens. */\n${CHARTS_JS.trim()}`;
const ASSETS = { "tokens.css": TOKENS_CSS, "helpers.js": HELPERS_JS, "toolkit.css": TOOLKIT_CSS, "toolkit.js": TOOLKIT_JS };
for (const [f, c] of Object.entries(ASSETS)) { put(`toolkit/${f}`, c); put(`${SKILL}/assets/${f}`, c); }

// ---------------------------------------------------------------- which functions does each snippet call?
const toolkitNames = new Set();
for (const m of CHARTS_JS.matchAll(/(?:^|\n|;)\s*(?:function\s+(\w+)\s*\(|(?:const|let)\s+(\w+)\s*=)/g)) toolkitNames.add(m[1] || m[2]);
const UTILITY = new Set(["sv", "compact", "sum", "median", "quantile", "niceStep", "yTicks", "setCategoryOrder", "catColor", "setPatterns", "setChartWidth", "fillSet", "showTip", "hideTip", "tipEl", "hoverColumns", "roving", "tipAt", "money0", "gbp", "monthName", "fmtDate", "h", "legend", "histBins", "histRange", "boxStats", "rankSeries"]);
const callsIn = snippet => {
  const seen = [];
  for (const m of snippet.matchAll(/(?<![.\w])([A-Za-z_]\w*)\s*\(/g)) if (toolkitNames.has(m[1]) && !seen.includes(m[1])) seen.push(m[1]);
  return seen;
};
// Pages that are assembled from plain markup and small helpers rather than one chart function.
const COMPOSED = { "/kpi-tiles": "markup + spark", "/small-multiples": "markup + spark" };
const mainFn = p => COMPOSED[p.path] || callsIn(p.snippet).find(n => !UTILITY.has(n)) || callsIn(p.snippet)[0] || "";
const helperCalls = p => COMPOSED[p.path] ? [] : callsIn(p.snippet).filter(n => n !== mainFn(p));
for (const k of Object.keys(COMPOSED)) if (!byPath.has(k)) problems.push(`COMPOSED lists ${k}, which is not a page.`);
for (const p of PAGES) if (!mainFn(p)) problems.push(`Could not work out which toolkit function the snippet for ${p.path} calls.`);

const md = t => t.replace(/(<\/?[a-z][^>]*>)/gi, "`$1`");
const groupOf = p => GROUPS.find(g => g.paths.includes(p.path));
const firstSentence = s => (s.match(/^.*?[.!?](?=\s|$)/) || [s])[0];

// ---------------------------------------------------------------- one page per chart
const chartMd = p => {
  const g = groupOf(p), fn = mainFn(p), others = helperCalls(p);
  return `${NOTE_MD}
# ${p.name}

${p.tag}

- **Function:** ${fn.includes(" ") ? fn.replace(/(\w+)$/, "`$1`") : `\`${fn}\``}
- **Group:** ${g.name}
- **Live demo:** [${SITE.replace("https://", "")}${p.path}](${SITE}${p.path}) (toggle the options, empty and one-point states)
- **Needs:** \`toolkit/tokens.css\`, \`toolkit/helpers.js\`, \`toolkit/toolkit.css\`, \`toolkit/toolkit.js\`. See [getting started](../getting-started.md).

## When to use it

${md(p.when)}

## Options

${p.opts.map(([k, v]) => `- \`${k}\`: ${md(v)}`).join("\n")}

## Example

\`\`\`js
${p.snippet}
\`\`\`

${others.length ? `Other toolkit functions used above: ${others.map(n => `\`${n}\``).join(", ")}. Names such as \`openMonth\` or \`openCategory\` in the example are your own callbacks, not part of the toolkit.\n\n` : "Names such as `openMonth` or `openCategory` in the example (where present) are your own callbacks, not part of the toolkit.\n\n"}## Keyboard and screen readers

${md(p.keys)}

## Edge cases

Empty, one-point and all-zero data are handled and drawn on purpose, not hidden. See [concepts](../concepts.md#edge-cases).

[All charts](README.md) · [Get the toolkit](../getting-started.md)
`;
};
// Inside the skill folder the toolkit files are in assets/, and the shared docs are one file (toolkit-api.md).
const inSkill = md => md
  .replaceAll("`toolkit/", "`assets/")
  .replace("(README.md)", "(../chart-index.md)")
  .replace("See [getting started](../getting-started.md).", "See [shared functions and conventions](../toolkit-api.md).")
  .replace("[concepts](../concepts.md#edge-cases)", "[conventions](../toolkit-api.md#edge-cases)")
  .replace("[Get the toolkit](../getting-started.md)", "[Shared functions](../toolkit-api.md)");
for (const p of PAGES) {
  const md = chartMd(p);
  put(`docs/charts/${slug(p)}.md`, md);
  put(`${SKILL}/references/charts/${slug(p)}.md`, inSkill(md));
}

// ---------------------------------------------------------------- index tables
const indexTable = (linkPrefix, linkSuffix = ".md") => GROUPS.map(g => `### ${g.name}

${g.blurb}

| Chart | Function | Use it for |
| --- | --- | --- |
${g.paths.map(x => byPath.get(x)).map(p => `| [${p.name}](${linkPrefix}${slug(p)}${linkSuffix}) | ${mainFn(p).includes(" ") ? mainFn(p).replace(/(\w+)$/, "`$1`") : "`" + mainFn(p) + "`"} | ${p.tag.replace(/\|/g, "\\|")} |`).join("\n")}
`).join("\n");
put("docs/charts/README.md", `${NOTE_MD}
# All ${PAGES.length} charts

Each page has the options, a copyable example and notes on keyboard use. For a live demo with the empty and one-point states, see [${SITE.replace("https://", "")}](${SITE}).

${indexTable("")}
[Back to the docs](../README.md)
`);
put(`${SKILL}/references/chart-index.md`, `${NOTE_MD}
# Chart index

${PAGES.length} chart types. Open the page for the chart you pick (options and a complete example) before writing code.

${indexTable("charts/")}
## Choosing between them

${PAGES.map(p => `- **${p.name}**: ${md(firstSentence(p.when))}`).join("\n")}
`);

// ---------------------------------------------------------------- the skill's toolkit reference and llms files come from the hand-written docs
const concepts = read("docs/concepts.md"), start = read("docs/getting-started.md"), api = read("docs/api.md");
put(`${SKILL}/references/toolkit-api.md`, `${NOTE_MD}\n${api.trim()}\n\n---\n\n${concepts.trim()}`.replace(/\]\(charts\/README\.md\)/g, "](chart-index.md)"));

const links = list => list.map(([t, u, d]) => `- [${t}](${u})${d ? `: ${d}` : ""}`).join("\n");
put("llms.txt", `# Product Scope Charts

> ${PAGES.length} SVG chart types for dashboards and reports, written from scratch with no libraries or dependencies. Copy one stylesheet and one script into any project. Accessible by default (keyboard, screen-reader labels, colour-blind-checked palette, optional patterns, a table view), light and dark themes, MIT licensed. All demo data is made up.

To build with it: copy the four files in toolkit/ into the project (design tokens, helpers, CSS, script), open the page for the chart you need, and call its function with arrays of numbers and a few options.

## Start here

${links([
  ["Getting started", `${RAW}/docs/getting-started.md`, "copy the toolkit, draw a first chart"],
  ["Concepts and conventions", `${RAW}/docs/concepts.md`, "theming, sizing, colours, accessibility, edge cases, CSP"],
  ["Shared functions and helpers", `${RAW}/docs/api.md`, "setChartWidth, setCategoryOrder, dataTable, spark, hbars and friends"],
  ["Everything in one file", `${RAW}/llms-full.txt`, "all of the above plus every chart's options and example"],
])}

## Toolkit files (copy these into your project)

${links([
  ["toolkit/tokens.css", `${RAW}/toolkit/tokens.css`, "design tokens, light and dark"],
  ["toolkit/helpers.js", `${RAW}/toolkit/helpers.js`, "h, money0, monthName, fmtDate, legend. Define before the script"],
  ["toolkit/toolkit.css", `${RAW}/toolkit/toolkit.css`, "chart styles"],
  ["toolkit/toolkit.js", `${RAW}/toolkit/toolkit.js`, "all the chart functions"],
])}

## Charts

${GROUPS.map(g => `### ${g.name}\n\n${links(g.paths.map(x => byPath.get(x)).map(p => [`${p.name} (${mainFn(p)})`, `${RAW}/docs/charts/${slug(p)}.md`, p.tag]))}`).join("\n\n")}

## Other

${links([
  ["Live demos", SITE, "every chart with options, empty and one-point states"],
  ["Claude skill", `${REPO}/tree/main/skills/productscope-charts`, "install it so Claude knows how to use these charts"],
  ["Source", REPO],
])}
`);

const stripGen = s => s.replace(/<!--[\s\S]*?-->\n?/g, "").trim();
put("llms-full.txt", `# Product Scope Charts: full documentation

${PAGES.length} SVG chart types. No libraries. MIT licensed. Source: ${REPO}. Live demos: ${SITE}.
The code to copy is in toolkit/ (tokens.css, helpers.js, toolkit.css, toolkit.js); fetch them from ${RAW}/toolkit/.

${stripGen(start)}

${stripGen(concepts)}

${stripGen(api)}

# Chart reference

${PAGES.map(p => stripGen(chartMd(p)).replace(/^# /, "## ").replace(/^## (When to use it|Options|Example|Keyboard and screen readers|Edge cases)$/gm, "### $1").replace(/\n\[All charts\][^\n]*$/, "")).join("\n\n")}
`);

// ---------------------------------------------------------------- write or check
if (problems.length) fail(); // problems found while building the files (tokens, for example)
const stale = [];
for (const [rel, content] of out) {
  const file = path.join(ROOT, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (current === content) continue;
  stale.push(rel);
  if (!CHECK) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); }
}
// generated files that no longer have a source (a chart that was removed or renamed)
for (const dir of ["docs/charts", `${SKILL}/references/charts`]) {
  const full = path.join(ROOT, dir);
  if (!fs.existsSync(full)) continue;
  for (const f of fs.readdirSync(full)) {
    const rel = `${dir}/${f}`;
    if (!out.has(rel)) { stale.push(rel + " (no longer generated)"); if (!CHECK) fs.unlinkSync(path.join(full, f)); }
  }
}
if (CHECK) {
  if (stale.length) {
    console.error("These generated files are out of date. Run `npm run docs` and commit the result:\n" + stale.map(s => "  - " + s).join("\n"));
    process.exit(1);
  }
  console.log(`Docs are up to date (${out.size} generated files).`);
} else {
  console.log(stale.length ? `Updated ${stale.length} of ${out.size} generated files.` : `Nothing to update (${out.size} generated files already current).`);
}
